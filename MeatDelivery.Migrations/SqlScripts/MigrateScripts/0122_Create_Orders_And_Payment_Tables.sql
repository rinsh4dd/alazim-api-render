-- 7. Create Procedure: dbo.PR_PREVIEW_CUSTOMER_ORDER
CREATE OR ALTER PROCEDURE dbo.PR_PREVIEW_CUSTOMER_ORDER
(
    @CUSTOMER_USER_ID BIGINT,
    @ADDRESS_ID       BIGINT
)
AS
BEGIN
    SET NOCOUNT ON;

    -- A. Company Config Coordinates & Delivery Rates
    SELECT TOP 1
        COMPANY_CONFIG_ID,
        COMPANY_NAME_EN,
        LATITUDE AS STORE_LATITUDE,
        LONGITUDE AS STORE_LONGITUDE,
        ADVANCE_DELIVERY_DAYS,
        DELIVERY_START_TIME,
        DELIVERY_END_TIME
    FROM dbo.COMPANY_CONFIG
    WHERE IS_ACTIVE = 1;

    -- B. Customer Address Details
    SELECT
        ADDRESS_ID,
        CUSTOMER_USER_ID,
        FIRST_NAME,
        LAST_NAME,
        ADDRESS_TYPE,
        CONTACT_NUMBER,
        BUILDING_NAME,
        VILLA_OR_FLAT_NO,
        STREET,
        AREA,
        LANDMARK,
        CITY,
        POSTAL_CODE,
        LATITUDE,
        LONGITUDE,
        IS_DEFAULT
    FROM dbo.CUSTOMER_ADDRESSES
    WHERE ADDRESS_ID = @ADDRESS_ID
      AND CUSTOMER_USER_ID = @CUSTOMER_USER_ID
      AND IS_ACTIVE = 1;

    -- C. Customer Active Cart Header
    SELECT 
        c.CART_ID,
        c.CUSTOMER_USER_ID,
        c.CART_STATUS,
        c.COUPON_ID,
        c.CREATED_AT
    FROM dbo.CARTS c
    WHERE c.CUSTOMER_USER_ID = @CUSTOMER_USER_ID
      AND c.CART_STATUS = 'ACTIVE';

    -- D. Cart Items with Product Pricing Snapshots
    SELECT 
        ci.CART_ITEM_ID,
        ci.CART_ID,
        ci.PRODUCT_ID,
        p.DOC_NO AS PRODUCT_CODE,
        p.PRODUCT_NAME_EN,
        p.PRODUCT_NAME_AR,
        img.PRIMARY_URL AS PRODUCT_IMAGE,
        ISNULL(u.UNIT_DESCRIPTION, 'Kilogram') AS UNIT_DESCRIPTION,
        ISNULL(pr.PRICE, 0.00) AS REGULAR_UNIT_PRICE,
        ISNULL(pr.PRICE, 0.00) AS SELLING_UNIT_PRICE,
        ci.QUANTITY,
        ci.SPECIAL_INSTRUCTIONS,
        ci.ITEM_STATUS
    FROM dbo.CART_ITEMS ci
    INNER JOIN dbo.CARTS c ON c.CART_ID = ci.CART_ID
    INNER JOIN dbo.PRODUCTS p ON p.PRODUCT_ID = ci.PRODUCT_ID
    LEFT JOIN dbo.MEASUREMENT_UNITS u ON u.UNIT_ID = p.UNIT_ID
    LEFT JOIN dbo.PRODUCT_PRICES pr ON pr.PRODUCT_ID = p.PRODUCT_ID AND pr.IS_ACTIVE = 1
    LEFT JOIN dbo.PRODUCT_IMAGES img ON img.PRODUCT_ID = p.PRODUCT_ID
    WHERE c.CUSTOMER_USER_ID = @CUSTOMER_USER_ID
      AND c.CART_STATUS = 'ACTIVE'
      AND ci.ITEM_STATUS = 'ACTIVE';

    -- E. Cart Item Customizations with Price Snapshots
    SELECT 
        cic.CART_ITEM_ID,
        co.CUSTOMIZATION_OPTION_ID,
        cg.GROUP_NAME_EN,
        cg.GROUP_NAME_AR,
        co.OPTION_CODE,
        co.OPTION_NAME_EN,
        co.OPTION_NAME_AR,
        ISNULL(co.PRICING_VALUE, 0.00) AS ADDITIONAL_PRICE
    FROM dbo.CART_ITEM_CUSTOMIZATIONS cic
    INNER JOIN dbo.CART_ITEMS ci ON ci.CART_ITEM_ID = cic.CART_ITEM_ID
    INNER JOIN dbo.CARTS c ON c.CART_ID = ci.CART_ID
    INNER JOIN dbo.CUSTOMIZATION_OPTIONS co ON co.CUSTOMIZATION_OPTION_ID = cic.CUSTOMIZATION_OPTION_ID
    INNER JOIN dbo.CUSTOMIZATION_GROUPS cg ON cg.CUSTOMIZATION_GROUP_ID = co.CUSTOMIZATION_GROUP_ID
    WHERE c.CUSTOMER_USER_ID = @CUSTOMER_USER_ID
      AND c.CART_STATUS = 'ACTIVE'
      AND ci.ITEM_STATUS = 'ACTIVE';
END;
GO
