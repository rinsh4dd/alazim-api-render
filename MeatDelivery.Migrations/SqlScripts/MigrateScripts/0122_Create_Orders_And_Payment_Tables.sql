BEGIN
    DECLARE @CompanyId BIGINT = (SELECT TOP 1 COMPANY_CONFIG_ID FROM dbo.COMPANY_CONFIG WHERE IS_ACTIVE = 1);
    
    INSERT INTO dbo.M_DOC_NO 
    (MDOC, DOCTYPE, DESCRIPTION, COMPANY_CONFIG_ID, PREFIX, SUFFIX, DIGIT_NO, START_DOCNO, PERIODWISE_YN, PERIOD_TYPE, IS_ACTIVE)
